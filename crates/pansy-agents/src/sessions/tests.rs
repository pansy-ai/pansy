#[test]
fn lists_each_agents_sessions() {
    let (home, _lock) = scratch();
    claude_session(home.path());
    codex_session(home.path());
    let all = list();
    let ids: Vec<&str> = all.iter().map(|s| s.id.as_str()).collect();
    // the latest first; nothing-said and orphaned threads left out
    assert_eq!(ids, [CLAUDE_ID, CODEX_ID]);

    let c = &all[0];
    assert_eq!(c.agent, "claude-code");
    assert_eq!(c.title, "Login bug fix");
    assert_eq!(c.cwd, "/work/app");
    assert_eq!(c.models, ["claude-sonnet-4-5"]);
    // a prompt and two replies: not the command, the tool's result or the made-up reply
    assert_eq!(c.messages, 3);
    // each reply once, and the subagent's
    assert_eq!(c.tokens.input, 21);
    assert_eq!(c.tokens.cache_read, 200);
    assert_eq!(c.tokens.output, 11);
    assert_eq!(
        c.resume,
        format!("cd '/work/app' && claude --resume {CLAUDE_ID}")
    );
    assert!(!c.active);
    assert_eq!(c.subagents.len(), 1);
    assert_eq!(c.subagents[0].id, "agent-a1");
    assert_eq!(c.subagents[0].title, "Find the login handlers");
    assert_eq!(c.subagents[0].kind, "Explore");
    assert_eq!(c.start.unwrap().to_rfc3339(), "2026-11-10T10:00:00+00:00");

    let x = &all[1];
    assert_eq!(x.agent, "codex");
    assert_eq!(x.title, "Health endpoint");
    assert_eq!(x.cwd, "/work/api");
    assert_eq!(x.models, ["gpt-5.1-codex"]);
    assert_eq!(x.messages, 2);
    // the last count, its spawned thread's added
    assert_eq!(x.tokens.input, 1100 + 100);
    assert_eq!(x.tokens.cache_read, 800);
    assert_eq!(x.tokens.reasoning, 40);
    assert_eq!(
        x.resume,
        format!("cd '/work/api' && codex resume {CODEX_ID}")
    );
    assert_eq!(x.subagents.len(), 1);
    assert_eq!(x.subagents[0].id, CODEX_KID);
    assert_eq!(x.subagents[0].title, "Review the endpoint");
}

