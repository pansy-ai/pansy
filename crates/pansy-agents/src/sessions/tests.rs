#[test]
fn reads_opencodes_older_files() {
    let (home, _lock) = scratch();
    let storage = home.path().join(".local/share/opencode/storage");
    let write = |rel: String, value: serde_json::Value| {
        let path = storage.join(rel);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(&path, value.to_string()).unwrap();
        aged(&path);
    };
    write(
        format!("session/0f3a/{OC_ROOT}.json"),
        json!({"id": OC_ROOT, "directory": "/work/oc", "title": "Flaky test hunt", "time": {"created": T, "updated": T + 9000}}),
    );
    write(
        format!("message/{OC_ROOT}/msg_1.json"),
        json!({"id": "msg_1", "role": "user", "time": {"created": T + 1000}}),
    );
    write(
        "part/msg_1/prt_1.json".into(),
        json!({"type": "text", "text": "Why does the login test flake?"}),
    );
    write(
        format!("message/{OC_ROOT}/msg_2.json"),
        json!({"id": "msg_2", "role": "assistant", "modelID": "gpt-5.1",
               "tokens": {"input": 1000, "output": 100, "reasoning": 20, "cache": {"read": 5000, "write": 0}},
               "time": {"created": T + 2000, "completed": T + 9000}}),
    );
    write(
        "part/msg_2/prt_2.json".into(),
        json!({"type": "text", "text": "It waits on a timer."}),
    );

    let s = find("opencode", OC_ROOT).unwrap();
    assert_eq!(s.title, "Flaky test hunt");
    assert_eq!(s.messages, 2);
    assert_eq!(s.tokens.cache_read, 5000);
    assert!(s.path.ends_with(&format!("{OC_ROOT}.json")));
    assert_eq!(
        said(&transcript("opencode", OC_ROOT, "").unwrap()),
        [
            ("user", "", "Why does the login test flake?"),
            ("assistant", "", "It waits on a timer."),
        ]
    );
    assert_eq!(search("a timer", 10)[0].id, OC_ROOT);

    // a database made from them is read in their place
    let db = oc_db(home.path());
    oc_session(
        &db,
        "ses_1a2b3c4d5e6fDDDDDDDDDDDDDD",
        None,
        "From the database",
    );
    oc_message(
        &db,
        "ses_1a2b3c4d5e6fDDDDDDDDDDDDDD",
        json!({"id": "msg_9", "role": "user", "time": {"created": T}}),
    );
    let ids: Vec<String> = list().into_iter().map(|s| s.id).collect();
    assert_eq!(ids, ["ses_1a2b3c4d5e6fDDDDDDDDDDDDDD"]);
}
