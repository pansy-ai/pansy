/// 2026-09-26 09:00 UTC, in OpenCode's milliseconds.
const T: i64 = 1_790_413_200_000;

/// OpenCode 1.2's tables, in WAL mode as OpenCode keeps them.
fn oc_db(home: &Path) -> rusqlite::Connection {
    let path = home.join(".local/share/opencode/opencode.db");
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    let db = rusqlite::Connection::open(path).unwrap();
    db.execute_batch(
        "PRAGMA journal_mode=WAL;
         CREATE TABLE session (id text PRIMARY KEY, project_id text NOT NULL, parent_id text, slug text NOT NULL,
             directory text NOT NULL, title text NOT NULL, version text NOT NULL, time_created integer NOT NULL,
             time_updated integer NOT NULL);
         CREATE TABLE message (id text PRIMARY KEY, session_id text NOT NULL, time_created integer NOT NULL,
             time_updated integer NOT NULL, data text NOT NULL);
         CREATE TABLE part (id text PRIMARY KEY, message_id text NOT NULL, session_id text NOT NULL,
             time_created integer NOT NULL, time_updated integer NOT NULL, data text NOT NULL);",
    )
    .unwrap();
    db
}

fn oc_session(db: &rusqlite::Connection, id: &str, parent: Option<&str>, title: &str) {
    db.execute(
        "INSERT INTO session VALUES (?1, 'p1', ?2, 'slug', '/work/oc', ?3, '1.2.0', ?4, ?4)",
        rusqlite::params![id, parent, title, T],
    )
    .unwrap();
}

fn oc_message(db: &rusqlite::Connection, session: &str, data: serde_json::Value) {
    let id = data["id"].as_str().unwrap().to_owned();
    let at = data["time"]["created"].as_i64().unwrap();
    db.execute(
        "INSERT INTO message VALUES (?1, ?2, ?3, ?3, ?4)",
        rusqlite::params![id, session, at, data.to_string()],
    )
    .unwrap();
}

fn oc_part(
    db: &rusqlite::Connection,
    session: &str,
    message: &str,
    id: &str,
    data: serde_json::Value,
) {
    db.execute(
        "INSERT INTO part VALUES (?1, ?2, ?3, 0, 0, ?4)",
        rusqlite::params![id, message, session, data.to_string()],
    )
    .unwrap();
}

