#[test]
fn deletes_into_the_trash_and_back() {
    let (home, _lock) = scratch();
    let main = claude_session(home.path());
    let before = fs::read(&main).unwrap();
    let folder = main.with_file_name(CLAUDE_ID);

    let t = trash::delete("claude-code", CLAUDE_ID).unwrap();
    assert!(!main.exists() && !folder.exists());
    assert!(find("claude-code", CLAUDE_ID).is_none());
    let listed = trash::list();
    assert_eq!(listed.len(), 1);
    assert_eq!(listed[0].title, "Login bug fix");
    assert_eq!(listed[0].items.len(), 2);
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mode = fs::metadata(home.path().join(".config/pansy/trash"))
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o777, 0o700);
    }

    // not over a file that is there again
    fs::write(&main, "new").unwrap();
    assert!(trash::restore(&t.key).is_err());
    fs::remove_file(&main).unwrap();

    trash::restore(&t.key).unwrap();
    assert_eq!(fs::read(&main).unwrap(), before);
    assert!(folder.join("subagents/agent-a1.jsonl").exists());
    assert!(trash::list().is_empty());
    assert!(find("claude-code", CLAUDE_ID).is_some());

    // erased for good only when asked
    let t = trash::delete("claude-code", CLAUDE_ID).unwrap();
    assert!(trash::purge("claude-code/../../x").is_err());
    trash::purge(&t.key).unwrap();
    assert!(trash::list().is_empty() && !main.exists());
}

#[test]
fn leaves_a_running_session_alone() {
    let (home, _lock) = scratch();
    codex_session(home.path());
    let kid = home.path().join(format!(
        ".codex/sessions/2026/11/09/rollout-2026-11-09T08-02-00-{CODEX_KID}.jsonl"
    ));
    // its spawned thread was written just now
    fs::File::options()
        .write(true)
        .open(&kid)
        .unwrap()
        .set_modified(SystemTime::now())
        .unwrap();
    assert!(find("codex", CODEX_ID).unwrap().active);
    let e = trash::delete("codex", CODEX_ID).unwrap_err();
    assert!(e.to_string().contains("may still be running"), "{e}");
    aged(&kid);
    let t = trash::delete("codex", CODEX_ID).unwrap();
    // the thread and the one it spawned
    assert_eq!(t.items.len(), 2);
    assert!(!kid.exists());
    trash::empty().unwrap();
}

