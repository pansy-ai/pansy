#[test]
fn reads_what_was_said() {
    let (home, _lock) = scratch();
    claude_session(home.path());
    codex_session(home.path());

    let turns = transcript("claude-code", CLAUDE_ID, "").unwrap();
    let said: Vec<(&str, &str, &str)> = turns
        .iter()
        .map(|t| (t.role, t.name.as_str(), t.text.as_str()))
        .collect();
    assert_eq!(
        said,
        [
            ("user", "", "/model opus"),
            (
                "user",
                "",
                "<pasted_content id=\"a1\">\nFix the login bug\n</pasted_content>"
            ),
            ("assistant", "", "Looking at the Login form."),
            ("tool", "Bash", "grep -rn login src"),
            ("reasoning", "", "hm"),
            ("assistant", "", "Fixed: the form now trims the e-mail."),
        ]
    );
    // a tool's input whole, and the result that answered it
    assert_eq!(
        turns[3].input,
        "{\n  \"command\": \"grep -rn login src\",\n  \"description\": \"Find it\"\n}"
    );
    assert_eq!(
        (turns[3].output.as_str(), turns[3].status),
        ("src/login.ts:3", "done")
    );
    let sub = transcript("claude-code", CLAUDE_ID, "agent-a1").unwrap();
    assert_eq!(sub.len(), 2);
    assert_eq!(sub[1].text, "Two handlers.");
    assert!(transcript("claude-code", CLAUDE_ID, "../../x").is_err());

    let turns = transcript("codex", CODEX_ID, "").unwrap();
    let said: Vec<(&str, &str, &str)> = turns
        .iter()
        .map(|t| (t.role, t.name.as_str(), t.text.as_str()))
        .collect();
    assert_eq!(
        said,
        [
            ("user", "", "Add a health endpoint"),
            ("tool", "shell", "ls src"),
            ("tool", "apply_patch", "src/health.rs"),
            ("assistant", "", "Added GET /health."),
        ]
    );
    assert_eq!(
        turns[1].input,
        "{\n  \"command\": [\n    \"bash\",\n    \"-lc\",\n    \"ls src\"\n  ]\n}"
    );
    assert_eq!(
        (turns[1].output.as_str(), turns[1].status),
        ("main.rs", "done")
    );
    // a patch as it is, and a command that exited with 1 failed
    assert!(turns[2].input.starts_with("*** Begin Patch\n*** Add File"));
    assert_eq!(turns[2].status, "error");
    assert_eq!(turns[2].output, "patch rejected");
    let kid = transcript("codex", CODEX_ID, CODEX_KID).unwrap();
    assert_eq!(kid[0].text, "Review the endpoint");
}

#[test]
fn says_where_each_turn_ended_for_the_phone() {
    let (home, _lock) = scratch();
    let claude = claude_session(home.path());
    let codex = codex_session(home.path());
    let line = |v: serde_json::Value| {
        use std::io::Write;
        move |path: &Path| {
            let mut f = fs::OpenOptions::new().append(true).open(path).unwrap();
            writeln!(f, "{v}").unwrap();
        }
    };
    line(
        json!({"timestamp": "2026-11-09T08:05:00.000Z", "type": "event_msg", "payload": {"type": "task_complete", "turn_id": "t1", "duration_ms": 240_000}}),
    )(&codex);
    line(
        json!({"timestamp": "2026-11-09T08:07:00.000Z", "type": "event_msg", "payload": {"type": "turn_aborted", "reason": "interrupted", "duration_ms": 5_000}}),
    )(&codex);
    line(
        json!({"type": "user", "cwd": "/work/app", "sessionId": CLAUDE_ID, "timestamp": "2026-11-10T10:07:00.000Z",
                "message": {"role": "user", "content": [{"type": "text", "text": "[Request interrupted by user]"}]}}),
    )(&claude);

    // Codex writes how long a turn took, and whether it was stopped
    let turns = timed_transcript("codex", CODEX_ID).unwrap();
    let ends: Vec<(Option<u64>, &str)> = turns
        .iter()
        .filter(|t| t.role == "end")
        .map(|t| (t.ms, t.status))
        .collect();
    assert_eq!(ends, [(Some(240_000), ""), (Some(5_000), "stopped")]);
    // Claude Code only that the user stopped one
    let turns = timed_transcript("claude-code", CLAUDE_ID).unwrap();
    let last = turns.last().unwrap();
    assert_eq!((last.role, last.status, last.ms), ("end", "stopped", None));
    // the window's transcript keeps none of it
    assert!(
        transcript("codex", CODEX_ID, "")
            .unwrap()
            .iter()
            .all(|t| t.role != "end")
    );
}

