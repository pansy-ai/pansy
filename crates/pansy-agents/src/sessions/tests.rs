fn said(turns: &[Turn]) -> Vec<(&str, &str, &str)> {
    turns
        .iter()
        .map(|t| (t.role, t.name.as_str(), t.text.as_str()))
        .collect()
}

#[test]
fn reads_opencodes_database() {
    let (home, _lock) = scratch();
    // OpenCode running: its connection open
    let db = oc_db(home.path());
    oc_fill(&db);
    let all = list();
    assert_eq!(all.len(), 1);
    let s = &all[0];
    assert_eq!((s.agent, s.id.as_str()), ("opencode", OC_ROOT));
    assert_eq!(s.title, "Why does the login test flake?");
    assert_eq!(s.cwd, "/work/oc");
    assert_eq!(s.models, ["gpt-5.1"]);
    assert_eq!(s.messages, 2);
    // its subagent's too; output with the reasoning
    assert_eq!(
        s.tokens,
        Tokens {
            input: 1040,
            output: 180,
            cache_read: 5700,
            cache_write: 300,
            reasoning: 20
        }
    );
    assert_eq!(
        s.resume,
        format!("cd '/work/oc' && opencode --session {OC_ROOT}")
    );
    assert!(s.path.ends_with("opencode.db"));
    assert!(!s.deletable && !s.active);
    assert_eq!(s.subagents.len(), 1);
    assert_eq!(s.subagents[0].id, OC_KID);
    assert_eq!(s.subagents[0].title, "Find the flaky handler");
    assert_eq!(s.subagents[0].kind, "explore");

    assert_eq!(
        said(&transcript("opencode", OC_ROOT, "").unwrap()),
        [
            ("user", "", "Why does  the login test\nflake?"),
            ("assistant", "", "Looking at the test."),
            ("tool", "bash", "npm test"),
            ("assistant", "", "It waits on a timer."),
        ]
    );
    let turns = transcript("opencode", OC_ROOT, "").unwrap();
    assert_eq!(
        (turns[2].output.as_str(), turns[2].status),
        ("1 failing", "done")
    );
    assert_eq!(
        said(&transcript("opencode", OC_ROOT, OC_KID).unwrap()),
        [("user", "", "Look for timers")]
    );
    let hits = search("WAITS on a", 10);
    assert_eq!(hits.len(), 1);
    assert_eq!(hits[0].text, "It waits on a timer.");
    assert!(search("50%_", 10).is_empty());

    // listed, never deleted: OpenCode keeps the database open
    let e = trash::delete("opencode", OC_ROOT).unwrap_err();
    assert!(e.to_string().contains("doesn't delete them"), "{e}");

    // a later reply is read, from memory no longer
    oc_message(
        &db,
        OC_ROOT,
        json!({"id": "msg_5", "role": "assistant", "modelID": "gpt-5.1",
               "tokens": {"input": 1, "output": 1, "cache": {"read": 0, "write": 0}},
               "time": {"created": T + 60_000, "completed": T + 61_000}}),
    );
    assert_eq!(find("opencode", OC_ROOT).unwrap().messages, 3);

    // OpenCode closed: its write-ahead log folded in and gone
    drop(db);
    assert_eq!(find("opencode", OC_ROOT).unwrap().tokens.input, 1041);
}

