export type Message = keyof typeof ZH_HANS;
export type Locale = "en" | "zh-Hans";
export type Choice = "system" | Locale;

const TABLES: Record<Locale, Partial<Record<Message, string>>> = { en: {}, "zh-Hans": ZH_HANS };

/** The languages Settings offers, each named in itself. */
export const LANGUAGES: { choice: Choice; name: string }[] = [
  { choice: "system", name: "System" },
  { choice: "en", name: "English" },
  { choice: "zh-Hans", name: "简体中文" },
];

function current(choice: Choice): Locale {
  if (choice !== "system") return choice;
  const system = systemLocale().toLowerCase();
  return system.startsWith("zh") ? "zh-Hans" : "en";
}

/** The window's language now. */
export const locale = (): Locale => current(language());

/** The choice saved in Settings. */
export const language = signal<Choice>(Prefs.language() as Choice);

/** Saves `choice` and shows the window in it; throws when it cannot be saved. */
export function setLanguage(choice: Choice) {
  Prefs.setLanguage(choice);
  language.set(choice);
}

/** The window's font on Windows, whose Segoe UI does not know Chinese. */
export function fontClass(): string {
  return platform.os === "windows" && current(language()) === "zh-Hans" ? "font-[Microsoft_YaHei_UI,Segoe_UI]" : "";
}

/** `message` in the window's language, with `%s`/`%d` replaced by `args` in order. */
export function tr(message: Message, ...args: (string | number)[]): string {
  const text = TABLES[current(language())][message] ?? message;
  let next = 0;
  return args.length ? text.replace(/%[sd]/g, () => String(args[next++] ?? "")) : text;
}

/** A string the core gives (a preset's note, a plan's name), in the window's language when the table has it. */
export function trCore(text: string): string {
  return text in ZH_HANS ? tr(text as Message) : text;
}

/** `tr` of `one` when `n` is 1, else of `many`: "1 model", "3 models". */
export function trn(n: number, one: Message, many: Message, ...args: (string | number)[]): string {
  return tr(n === 1 ? one : many, ...args);
}
