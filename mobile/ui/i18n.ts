export type Message = keyof typeof ZH_HANS;
export type Locale = "en" | "zh-Hans";
export type Choice = "system" | Locale;

const TABLES: Record<Locale, Partial<Record<Message, string>>> = { en: {}, "zh-Hans": ZH_HANS };

const KEY = "pansy.language";

/** The choice saved in Settings. */
export const language = signal<Choice>("system");

function current(choice: Choice): Locale {
  if (choice !== "system") return choice;
  return systemLocale().toLowerCase().startsWith("zh") ? "zh-Hans" : "en";
}

/** The app's language now. */
export const locale = (): Locale => current(language());

/** Reads the saved choice. */
export async function loadLanguage() {
  const saved = await Storage.getItem(KEY);
  if (saved === "en" || saved === "zh-Hans" || saved === "system") language.set(saved);
}

/** Saves `choice` and shows the app in it. */
export function setLanguage(choice: Choice) {
  language.set(choice);
  void Storage.setItem(KEY, choice);
}

/** `message` in the app's language, with `%s`/`%d` replaced by `args` in order. */
export function tr(message: Message, ...args: (string | number)[]): string {
  const text = TABLES[locale()][message] ?? message;
  let next = 0;
  return args.length ? text.replace(/%[sd]/g, () => String(args[next++] ?? "")) : text;
}

/** `tr` of `one` when `n` is 1, else of `many`. */
export function trn(n: number, one: Message, many: Message, ...args: (string | number)[]): string {
  return tr(n === 1 ? one : many, ...args);
}
