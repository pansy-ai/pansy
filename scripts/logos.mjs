// Writes desktop/ui/logos/index.ts from the SVG logos beside it (LobeHub's
// icons and the vendors' own, as magpie ships them): each as SVG text, sized
// 24 and without its title, prolog or comments, so ui/parts.tsx draws it as
// an image in the theme's ink when it is drawn in `currentColor`. The PNG
// ones beside them are imported by ui/parts.tsx.
//   node scripts/logos.mjs
import fs from "node:fs";
import path from "node:path";

const dir = path.join(path.dirname(new URL(import.meta.url).pathname), "../desktop/ui/logos");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort();
let out = `// Generated by scripts/logos.mjs from the SVG files beside it: provider and
// agent logos (LobeHub's icons, MIT; the marks are their owners'). Do not edit.

/** Each logo's SVG; one drawn in \`currentColor\` takes the theme's ink. */
export const LOGOS = {
`;
for (const file of files) {
  let svg = fs
    .readFileSync(path.join(dir, file), "utf8")
    .replace(/<\?xml.*?\?>/s, "")
    .replace(/<!--.*?-->/gs, "")
    .replace(/<title>.*?<\/title>/s, "")
    .replace(/\s(width|height)="1em"/g, ' $1="24"')
    .replace(/\sstyle="[^"]*"/, "")
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();
  // One with no size of its own (CherryIN's) is given the others'.
  if (!/^<svg[^>]*\swidth=/.test(svg)) svg = svg.replace(/^<svg/, '<svg width="24" height="24"');
  const name = file.replace(/\.svg$/, "");
  const key = /^[a-z]+$/.test(name) ? name : JSON.stringify(name);
  out += `  ${key}: ${JSON.stringify(svg)},\n`;
}
out += "};\n";
fs.writeFileSync(path.join(dir, "index.ts"), out);
console.log(`${files.length} logos`);
